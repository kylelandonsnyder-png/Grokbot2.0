function txn(
  id: string,
  accountId: string,
  day: string,
  merchant: string,
  amount: number,
  categoryId: string,
  extras: Partial<Transaction> = {},
): Transaction {
  return {
    id,
    accountId,
    date: day,
    merchant,
    amount,
    categoryId,
    pending: false,
    isTransfer: categoryId === 'cat_transfer',
    ...extras,
  };
}

